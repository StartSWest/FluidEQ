/**
 * `resolve_chain` and its grammar, held to the same config layout
 * `apoConfigReader.ts` reads: includes, `Device:` guards, and the five
 * commands FluidEQ writes. The file system here is a `std::map`, not disk —
 * this library never touches a Windows API, so the test does not need to
 * either.
 */

